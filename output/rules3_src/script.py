def knocks(ch, sc):
    return [round(x["start"] + k, 3) for x in ch if x["style"] == "k" for k in (0.1, 0.75, 1.4)]


def EVENTS(sc, ch):
    c = lambda s, i: [x for x in ch if x["scene"] == s][i]["start"]
    s = lambda n: sc[n]["start"]
    ev = [("knock", k, 1.0) for k in knocks(ch, sc)]
