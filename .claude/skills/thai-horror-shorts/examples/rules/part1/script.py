def knocks(ch, sc):
    out = []
    for x in ch:
        if x["style"] == "k":
            fast = x["scene"] == 9
            out += [round(x["start"] + k, 3) for k in ((0.05, 0.3, 0.55, 0.8, 1.05, 1.3, 1.55) if fast else (0.1, 0.75, 1.4))]
